gato = 10 
cachorro = 5.5
dinossauro = 10

# ==
if gato == 10:
    print("É 10 mesmo")

# !=
if cachorro != 6:
    print("É diferente")

# <=
if gato <= dinossauro:
    print("É igual")

# >=
if cachorro >= gato:
    print("OK")
else:
    print("Não OK")

# >
if cachorro > gato:
    print("É verdade")
else:
    print("É mentira")

# <
if cachorro < gato:
    print("É verdade")
else:
    print("É mentira")

